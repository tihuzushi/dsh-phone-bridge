// Builds lib/client.js from src/mobile-ui.{css,js}.
//
// The DSH web client loads plugin modules through window.__ModuleLoader__.load,
// so the browser half must register itself that way. Everything the shell needs
// is inlined to keep the package a single self-contained file.
//
//   node build.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.dirname(fileURLToPath(import.meta.url))
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'))
const css = fs.readFileSync(path.join(ROOT, 'src', 'mobile-ui.css'), 'utf8')
const ui = fs.readFileSync(path.join(ROOT, 'src', 'mobile-ui.js'), 'utf8')
const settings = fs.readFileSync(path.join(ROOT, 'src', 'settings-section.js'), 'utf8')
const out = path.join(ROOT, 'lib', 'client.js')

const banner = `// Generated by build.mjs from src/mobile-ui.css + src/mobile-ui.js + src/settings-section.js — do not edit by hand.
// Rebuild: node build.mjs
`

const body = `${banner}window.__ModuleLoader__.load({
	id: ${JSON.stringify(pkg.name)},
	factory: function (require) {
		var module = { exports: {} };
		var exports = module.exports;

		var CSS = ${JSON.stringify(css)};

		function runMobileUi() {
${ui}
		}

${settings}

		// Only take over phone-sized clients. The desktop app and desktop browsers
		// must keep the stock layout, so anything that is neither the HARNESS Phone
		// WebView (window.HarnessNative) nor an Android user agent stays untouched.
		function isPhoneClient() {
			try {
				if (window.HarnessNative) return true;
				return /Android/i.test(navigator.userAgent || "");
			} catch (_) {
				return false;
			}
		}

		function injectStyle() {
			if (document.getElementById("hp-mobile-style")) return;
			var style = document.createElement("style");
			style.id = "hp-mobile-style";
			style.textContent = CSS;
			(document.head || document.documentElement).appendChild(style);
		}

		function boot() {
			if (window.__hpMobileReady) return true;
			if (!document.body) return false;
			if (isPhoneClient()) {
				try {
					injectStyle();
					runMobileUi();
				} catch (error) {
					// A broken shell must never leave the phone with a half-applied UI.
					try { console.error("[dsh-phone-bridge] mobile shell failed to start", error); } catch (_) {}
				}
			} else {
				// Desktop: add the "DSH Phone Assistant" settings section.
				try {
					runSettingsSection();
				} catch (error) {
					try { console.error("[dsh-phone-bridge] settings section failed to start", error); } catch (_) {}
				}
			}
			return true;
		}

		function start() {
			if (boot()) return;
			document.addEventListener("DOMContentLoaded", boot, { once: true });
			var tries = 0;
			var timer = setInterval(function () {
				tries += 1;
				if (boot() || tries > 40) clearInterval(timer);
			}, 250);
		}

		start();

		exports.apply = function apply() {
			boot();
		};
		exports.inject = [];

		return module.exports;
	}
});
`

fs.mkdirSync(path.dirname(out), { recursive: true })
fs.writeFileSync(out, body, 'utf8')
console.log(`built ${path.relative(ROOT, out)} (${body.length} bytes) for ${pkg.name}@${pkg.version}`)
